/**
 * Pure helpers for the InfraFlow capability sync.
 *
 * deriveCapabilities() reduces a ModelInfo[] (the shape of GET /v1/models) into
 * the per-provider input-packet vocabulary the diagram streams (Core-3: text /
 * image / multi) plus the set of output modalities it produces (image, video,
 * and/or model3d — many providers do more than one). capabilitiesFromCatalog()
 * runs it over the shipped `models/*.yaml` rows, read the way the gateway
 * projects them, and is the source of the committed capabilities.generated.ts.
 */

/** @typedef {{ text: boolean, image: boolean, multi: boolean }} InputVocab */
/** @typedef {{ image: boolean, video: boolean, model3d: boolean }} OutputModalities */
/** @typedef {{ provider: string, inputs: InputVocab, outputs: OutputModalities, source: boolean }} ProviderCapability */

/** Reduce a ModelInfo[] (from GET /v1/models) to a provider→capability map. */
export function deriveCapabilities(models) {
  /** @type {Map<string, {text:boolean,image:boolean,multi:boolean,source:boolean,hasImage:boolean,hasVideo:boolean,has3d:boolean}>} */
  const acc = new Map();
  for (const m of models) {
    const cap = m.capabilities ?? {};
    const acceptsRef = Boolean(
      cap.supports_image_to_image ||
      cap.supports_image_to_video ||
      cap.supports_inpainting ||
      cap.supports_first_frame ||
      cap.supports_last_frame ||
      cap.supports_image_to_3d ||
      cap.supports_multiview_to_3d ||
      cap.supports_background_removal ||
      cap.supports_segmentation
    );
    const maxImages = Number(cap.max_images ?? 1);
    const v = acc.get(m.provider) ?? { text: false, image: false, multi: false, source: false, hasImage: false, hasVideo: false, has3d: false };
    if (cap.supports_text_to_image || cap.supports_text_to_video || cap.supports_text_to_3d) v.text = true;
    if (acceptsRef) v.image = true;
    if (maxImages >= 2) { v.multi = true; v.image = true; }
    if (cap.supports_source_model || cap.supports_source_video) v.source = true;
    if (m.media_type === 'video') v.hasVideo = true;
    if (m.media_type === 'image') v.hasImage = true;
    if (m.media_type === 'model3d') v.has3d = true;
    acc.set(m.provider, v);
  }
  /** @type {Record<string, ProviderCapability>} */
  const out = {};
  for (const [provider, v] of acc) {
    // A spoke is never empty, unless the provider works only on an existing
    // mesh or clip (meshy): then it takes a source, not text.
    const text = v.text || (!v.image && !v.multi && !v.source);
    const anyOut = v.hasImage || v.hasVideo || v.has3d; // never emit a modality-less node
    out[provider] = {
      provider,
      inputs: { text, image: v.image, multi: v.multi },
      outputs: { image: v.hasImage || !anyOut, video: v.hasVideo, model3d: v.has3d },
      source: v.source,
    };
  }
  return out;
}

/** Render a provider→capability map to the committed TS module (stable order). */
export function renderGeneratedTs(caps) {
  const ids = Object.keys(caps).sort();
  const entries = ids.map((id) => {
    const c = caps[id];
    const i = c.inputs;
    const o = c.outputs;
    return `  ${JSON.stringify(id)}: { provider: ${JSON.stringify(c.provider)}, inputs: { text: ${i.text}, image: ${i.image}, multi: ${i.multi} }, outputs: { image: ${o.image}, video: ${o.video}, model3d: ${o.model3d} }, source: ${c.source} },`;
  });
  return `// GENERATED by scripts/sync-capabilities.mjs — do not edit by hand.
// Run \`npm run sync-capabilities\` to refresh it from models/*.yaml.
export interface ProviderCapability {
  /** registry provider id, e.g. "stability" */
  provider: string;
  /** accepted input packet shapes (Core-3) */
  inputs: { text: boolean; image: boolean; multi: boolean };
  /** output modalities this provider can produce (many do both) */
  outputs: { image: boolean; video: boolean; model3d: boolean };
  /**
   * works on an existing mesh or clip (a source_model or source_video param).
   * A provider that only does that (meshy) has every input false: \`inputs\` is
   * never empty only for a provider with no source.
   */
  source: boolean;
}

export const PROVIDER_CAPABILITIES: Record<string, ProviderCapability> = {
${entries.join('\n')}
};
`;
}

/**
 * One catalog row as GET /v1/models describes it: the fields deriveCapabilities
 * reads, projected as litegen-core's `project_model_info` does (a role named
 * `mask` means inpainting, `first_frame` / `last_frame` keyframes, and
 * `ref_inputs.max_total` the reference images, 1 when the row takes none; a
 * source is a param named `source_model` / `source_video` of that kind, and
 * segmentation a `segment` task with a `prompts` param of kind
 * `segmentation_prompts`).
 */
export function modelInfoFromCatalog(m) {
  const cap = m.capabilities ?? {};
  const ri = m.ref_inputs;
  const roles = ri?.roles ?? {};
  const params = m.params ?? {};
  return {
    provider: m.provider,
    media_type: m.media_type,
    capabilities: {
      supports_text_to_image: cap.text_to_image === true,
      supports_image_to_image: cap.image_to_image === true,
      supports_inpainting: 'mask' in roles,
      supports_text_to_video: cap.text_to_video === true,
      supports_image_to_video: cap.image_to_video === true,
      supports_first_frame: 'first_frame' in roles,
      supports_last_frame: 'last_frame' in roles,
      supports_text_to_3d: cap.text_to_3d === true,
      supports_image_to_3d: cap.image_to_3d === true,
      supports_multiview_to_3d: cap.multiview_to_3d === true,
      supports_background_removal: cap.background_removal === true,
      supports_segmentation: m.task === 'segment' && params.prompts?.kind === 'segmentation_prompts',
      supports_source_model: params.source_model?.kind === 'source_model',
      supports_source_video: params.source_video?.kind === 'source_video',
      max_images: ri?.max_total ?? 1,
    },
  };
}

/** The provider→capability map of the shipped catalog (the mock provider left out). */
export function capabilitiesFromCatalog(rows) {
  return deriveCapabilities(rows.filter((m) => m.provider !== 'mock').map(modelInfoFromCatalog));
}
