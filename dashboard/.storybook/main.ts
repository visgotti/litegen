  stories: ['../src/**/*.stories.@(ts|tsx)', '../../packages/3d-viewer/src/**/*.stories.@(ts|tsx)'],
  addons: [],
  framework: { name: '@storybook/react-vite', options: {} },
  // Real GLB/PNG bytes generated by fixtures/make_fixtures.py, served at
  // /fixtures/ so the 3D stories render actual meshes rather than placeholders.
