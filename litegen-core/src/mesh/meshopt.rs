    #[test]
    fn stride_rules_are_enforced() {
        let stride = |why: String| assert!(why.contains("byteStride"), "{why}");
        // ATTRIBUTES: a multiple of 4, from 4 to 256. The ends decode (an
        // empty view is a header and a tail).
        for bad in [0, 2, 6, 255, 258, 260, 512] {
            stride(refused(ATTR_V1_STREAM, 72, bad, Mode::Attributes, Filter::None));
        }
        for good in [4, 256] {
            let empty: Vec<u8> = [0xa0].into_iter().chain(std::iter::repeat_n(0, good.max(32))).collect();
            assert_eq!(decode(&empty, 0, good, Mode::Attributes, Filter::None), Vec::<u8>::new(), "byteStride {good}");
        }
        // TRIANGLES and INDICES: 2 or 4.
        let triangles = TRIANGLES_DECODED_U32.len();
        for bad in [0, 1, 3, 6, 8] {
            stride(refused(TRIANGLES_STREAM, triangles, bad, Mode::Triangles, Filter::None));
            stride(refused(INDICES_STREAM, INDICES_DECODED_U32.len(), bad, Mode::Indices, Filter::None));
        }
        // TRIANGLES: a whole number of triangles.
        let why = refused(TRIANGLES_STREAM, triangles + 1, 4, Mode::Triangles, Filter::None);
        assert!(why.contains("count"), "{why}");

        // Each filter's strides, on streams that decode at those strides
        // with no filter: OCTAHEDRAL 4 or 8, QUATERNION 8, EXPONENTIAL a
        // multiple of 4, COLOR 4 or 8.
        assert!(decode_view(ATTR_V1_STREAM, 72, 16, Mode::Attributes, Filter::None).is_ok());
        assert!(decode_view(EXP_STREAM, 16, 12, Mode::Attributes, Filter::None).is_ok());
        for filter in [Filter::Octahedral, Filter::Quaternion, Filter::Color] {
            stride(refused(ATTR_V1_STREAM, 72, 16, Mode::Attributes, filter));
            stride(refused(EXP_STREAM, 16, 12, Mode::Attributes, filter));
        }
        stride(refused(OCT8_STREAM, 16, 4, Mode::Attributes, Filter::Quaternion));
        assert!(decode_view(ATTR_V1_STREAM, 72, 16, Mode::Attributes, Filter::Exponential).is_ok(), "EXPONENTIAL takes any multiple of 4");

        // A filter on an index mode.
        for filter in [Filter::Octahedral, Filter::Quaternion, Filter::Exponential, Filter::Color] {
            let why = refused(TRIANGLES_STREAM, triangles, 4, Mode::Triangles, filter);
            assert!(why.contains("filter"), "{why}");
            let why = refused(INDICES_STREAM, INDICES_DECODED_U32.len(), 4, Mode::Indices, filter);
            assert!(why.contains("filter"), "{why}");
        }
    }

