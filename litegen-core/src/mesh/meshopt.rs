    /// An ATTRIBUTES stream's structure, read from its bytes alone (nothing
    /// is decoded): each block's element count, each lane's control mode and
    /// group header modes, the channel modes, and how many deltas each bit
    /// width escapes. The mode tests use it to show their stream holds their
    /// case. It is written from Appendix A, apart from the decoder.
    struct Shape {
        blocks: Vec<Block>,
        channels: Vec<u8>,
        /// Escaped deltas, indexed by bits per delta (1, 2 and 4).
        escaped: [usize; 5],
    }
    struct Block {
        elements: usize,
        control: Vec<u8>,
        modes: Vec<Vec<u8>>,
    }

    fn shape(stream: &[u8], count: usize, stride: usize) -> Shape {
        let v1 = stream[0] == 0xa1;
        let tail = stride + if v1 { stride / 4 } else { 0 };
        let data_end = stream.len() - tail.max(if v1 { 24 } else { 32 });
        let block_elements = ((8192 / stride) & !15).min(256);
        let (mut at, mut start) = (1, 0);
        let (mut blocks, mut escaped) = (Vec::new(), [0; 5]);
        while start < count {
            let elements = (count - start).min(block_elements);
            let groups = elements.div_ceil(16);
            let control: Vec<u8> = (0..stride).map(|lane| if v1 { (stream[at + lane / 4] >> (lane % 4 * 2)) & 3 } else { 0 }).collect();
            if v1 {
                at += stride / 4;
            }
            let mut modes = Vec::new();
            for &ctrl in &control {
                let mut lane = Vec::new();
                match ctrl {
                    2 => {}
                    3 => at += elements,
                    _ => {
                        let header = at;
                        at += groups.div_ceil(4);
                        for g in 0..groups {
                            let mode = (stream[header + g / 4] >> (g % 4 * 2)) & 3;
                            lane.push(mode);
                            let table: [usize; 4] = if v1 { [[0, 1, 2, 4], [1, 2, 4, 8]][usize::from(ctrl)] } else { [0, 2, 4, 8] };
                            let bits = table[usize::from(mode)];
                            if bits == 8 {
                                at += 16;
                            } else if bits > 0 {
                                let packed = &stream[at..at + 2 * bits];
                                let value = |m: usize| match bits {
                                    1 => (packed[m / 8] >> (m % 8)) & 1,
                                    2 => (packed[m / 4] >> (6 - 2 * (m % 4))) & 3,
                                    _ => (packed[m / 2] >> (4 - 4 * (m % 2))) & 15,
                                };
                                let sentinel = (1u8 << bits) - 1;
                                let escapes = (0..16).filter(|&m| value(m) == sentinel).count();
                                escaped[bits] += escapes;
                                at += 2 * bits + escapes;
                            }
                        }
                    }
                }
                modes.push(lane);
            }
            blocks.push(Block { elements, control, modes });
            start += elements;
        }
        assert_eq!(at, data_end, "the blocks end where the padded tail begins");
        let channels = if v1 { stream[stream.len() - stride / 4..].to_vec() } else { Vec::new() };
        Shape { blocks, channels, escaped }
    }

    /// The varints of an INDICES stream's data, with each one's length.
    fn varints(data: &[u8]) -> Vec<(u32, usize)> {
        let (mut out, mut at) = (Vec::new(), 0);
        while at < data.len() {
            let (mut v, mut len) = (0u32, 0);
            loop {
                let b = data[at + len];
                v |= u32::from(b & 0x7f).wrapping_shl(7 * len as u32);
                len += 1;
                if b < 0x80 {
                    break;
                }
            }
            out.push((v, len));
            at += len;
        }
        out
    }

