//! meshopt-compressed glTF buffer views, decoded: `EXT_meshopt_compression`
//! and `KHR_meshopt_compression`.
//!
//! # Why
//!
//! gltfpack, the most common glTF optimiser, writes meshopt by default, and a
//! GLB whose views can't be decoded is refused after the vendor has billed.
//! glb.rs hands each compressed bufferView it reads here, once, and reads its
//! accessors from the bytes this returns.
//!
//! # What it decodes
//!
//! All three modes and all four filters of `KHR_meshopt_compression`, whose
//! Appendix C makes it the superset: it keeps `EXT_meshopt_compression`'s
//! bitstream (attribute format v0, header `0xa0`) and adds format v1 (`0xa1`,
//! with control modes and channel modes) and the COLOR filter. The decoder is
//! extension-agnostic; whether an `EXT_meshopt_compression` view may use v1 or
//! COLOR is the caller's rule.
//!
//! - ATTRIBUTES (Appendix A, mode 0): blocks of up to
//!   `min((8192 / byteStride) & !15, 256)` elements, each byte lane
//!   delta-coded in groups of 16 at 0, 1, 2, 4 or 8 bits a delta, the first
//!   against a baseline element stored in the tail.
//! - TRIANGLES (mode 1, header `0xe1`): a code byte per triangle over an edge
//!   FIFO and a vertex FIFO, varint extras, and a 16-byte code table.
//! - INDICES (mode 2, header `0xd1`): zig-zag varint deltas from two baselines.
//! - Filters (Appendix B), applied after decoding, to ATTRIBUTES only:
//!   OCTAHEDRAL, QUATERNION, EXPONENTIAL and COLOR. They compute in f32, as
//!   the appendix's pseudo-code does. meshoptimizer's JS reference decoder
//!   computes in f64, so a filtered component can differ from its reading by
//!   one unit in the last place, which the appendix allows. EXPONENTIAL is
//!   exact in both.
//!
//! It follows the spec's appendices, not meshoptimizer's SIMD decoders. The
//! tests compare it with meshoptimizer's JS reference decoder
//! (`js/meshopt_decoder_reference.js`) on streams that
//! `scripts/mesh-verify/meshopt-vectors.mjs` builds.
//!
//! @see <https://github.com/KhronosGroup/glTF/blob/main/extensions/2.0/Khronos/KHR_meshopt_compression/README.md>
//! @see <https://github.com/KhronosGroup/glTF/blob/main/extensions/2.0/Vendor/EXT_meshopt_compression/README.md>
//!
//! # Hostile input
//!
//! - The arguments are checked before anything is sized from them: the
//!   spec's byteStride rules, `count % 3` for TRIANGLES, filters on
//!   ATTRIBUTES only, the header byte, and the fewest bytes a stream of
//!   `count` elements can take. Only then is the output allocated, at exactly
//!   `count × byteStride` bytes, which the caller has charged to its budget.
//! - Every read is bounded by the stream. A stream that ends early, or leaves
//!   bytes before its tail, is `Malformed`, as the spec says.
//! - The spec's other validity rules hold too, where meshoptimizer's decoders
//!   are lenient: an invalid channel mode, a code table with a `0xf` nibble
//!   or non-zero last entries, a FIFO entry read before any triangle wrote
//!   it, and a varint longer than five bytes are `Malformed`.
//! - Decoded indices aren't range-checked here: they index vertex data this
//!   module never sees, so the caller checks them, as it does every index.
//! - Work is linear in the output: one pass over the stream, then one over
//!   the output for a filter.

use super::MeshError;

/// A compressed view's `mode`: which of Appendix A's bitstreams it holds.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    /// `"ATTRIBUTES"`: vertex data and any other run of equal-sized elements.
    Attributes,
    /// `"TRIANGLES"`: triangle-list indices.
    Triangles,
    /// `"INDICES"`: any other index data.
    Indices,
}

/// A compressed view's `filter`: the transform Appendix B applies after
/// decoding.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Filter {
    /// `"NONE"`, the default: the decoded bytes as they are.
    None,
    /// `"OCTAHEDRAL"`: unit vectors, 4 or 8 bytes each.
    Octahedral,
    /// `"QUATERNION"`: unit quaternions, 8 bytes each.
    Quaternion,
    /// `"EXPONENTIAL"`: 32-bit floats from an exponent and a mantissa.
    Exponential,
    /// `"COLOR"`: YCoCg colours, 4 or 8 bytes each. KHR only.
    Color,
}

/// Decodes one compressed view: `count` elements of `stride` bytes from
/// `data`, the extension's own byte range.
///
/// Callers charge their decode budget for `count × stride` bytes first. Once
/// the arguments pass the checks, this allocates exactly that many. glb.rs
/// charges them to `MAX_DECODED_VALUES`, four bytes a value.
pub fn decode_view(data: &[u8], count: usize, stride: usize, mode: Mode, filter: Filter) -> Result<Vec<u8>, MeshError> {
    check_layout(count, stride, mode, filter)?;
    let Some(&header) = data.first() else {
        return Err(malformed(format_args!("the {} stream ends early: it is empty", mode.name())));
    };
    check_header(header, mode)?;
    let len = count.checked_mul(stride).ok_or_else(|| malformed(format_args!("count {count} × byteStride {stride} overflows")))?;
    if data.len() < fewest_bytes(count, stride, mode, header == 0xa1) {
        return Err(ends_early(mode));
    }
    // The tail-only refusals, before the output is sized: a refused view
    // allocates nothing (final review, Minor 5). `fewest_bytes` has held
    // the stream to its tail already.
    match mode {
        Mode::Attributes if header == 0xa1 => check_channel_modes(data, stride)?,
        Mode::Triangles => check_code_table(data)?,
        _ => {}
    }
    let mut out = vec![0u8; len];
    match mode {
        Mode::Attributes => decode_attributes(data, count, stride, header == 0xa1, &mut out)?,
        Mode::Triangles => decode_triangles(data, count, stride, &mut out)?,
        Mode::Indices => decode_indices(data, count, stride, &mut out)?,
    }
    apply_filter(&mut out, stride, filter);
    Ok(out)
}

/// Appendix A's bits a delta, by group header mode: v0's, then v1's under
/// control modes 0 and 1.
const BITS_V0: [usize; 4] = [0, 2, 4, 8];
const BITS_V1: [[usize; 4]; 2] = [[0, 1, 2, 4], [1, 2, 4, 8]];
/// The fewest bytes an ATTRIBUTES tail takes: it is padded to this.
const TAIL_MIN_V0: usize = 32;
const TAIL_MIN_V1: usize = 24;
/// TRIANGLES' tail: its code table.
const CODE_TABLE_LEN: usize = 16;
/// INDICES' tail: padding.
const INDICES_TAIL_LEN: usize = 4;

impl Mode {
    fn name(self) -> &'static str {
        match self {
            Mode::Attributes => "ATTRIBUTES",
            Mode::Triangles => "TRIANGLES",
            Mode::Indices => "INDICES",
        }
    }
}

impl Filter {
    fn name(self) -> &'static str {
        match self {
            Filter::None => "NONE",
            Filter::Octahedral => "OCTAHEDRAL",
            Filter::Quaternion => "QUATERNION",
            Filter::Exponential => "EXPONENTIAL",
            Filter::Color => "COLOR",
        }
    }
}

fn malformed(detail: std::fmt::Arguments) -> MeshError {
    MeshError::Malformed(format!("meshopt: {detail}"))
}

fn ends_early(mode: Mode) -> MeshError {
    malformed(format_args!("the {} stream ends early", mode.name()))
}

/// The extension's JSON constraints on `byteStride`, `count` and `filter`.
fn check_layout(count: usize, stride: usize, mode: Mode, filter: Filter) -> Result<(), MeshError> {
    match mode {
        Mode::Attributes if !stride.is_multiple_of(4) || !(4..=256).contains(&stride) => {
            return Err(malformed(format_args!("ATTRIBUTES byteStride {stride} is not a multiple of 4 from 4 to 256")));
        }
        Mode::Attributes => {}
        Mode::Triangles | Mode::Indices => {
            if stride != 2 && stride != 4 {
                return Err(malformed(format_args!("{} byteStride {stride} is not 2 or 4", mode.name())));
            }
            if filter != Filter::None {
                return Err(malformed(format_args!("a {} filter on a {} view: filters apply to ATTRIBUTES only", filter.name(), mode.name())));
            }
            if mode == Mode::Triangles && !count.is_multiple_of(3) {
                return Err(malformed(format_args!("TRIANGLES count {count} is not a multiple of 3")));
            }
        }
    }
    let (fits, wanted) = match filter {
        // EXPONENTIAL takes a multiple of 4, which every ATTRIBUTES byteStride is.
        Filter::None | Filter::Exponential => (true, ""),
        Filter::Octahedral | Filter::Color => (stride == 4 || stride == 8, "4 or 8"),
        Filter::Quaternion => (stride == 8, "8"),
    };
    if !fits {
        return Err(malformed(format_args!("{} needs byteStride {wanted}, not {stride}", filter.name())));
    }
    Ok(())
}

fn check_header(header: u8, mode: Mode) -> Result<(), MeshError> {
    let (fits, wanted) = match mode {
        Mode::Attributes => (header == 0xa0 || header == 0xa1, "0xa0 or 0xa1"),
        Mode::Triangles => (header == 0xe1, "0xe1"),
        Mode::Indices => (header == 0xd1, "0xd1"),
    };
    if !fits {
        return Err(malformed(format_args!("the {} stream's header is 0x{header:02x}, not {wanted}", mode.name())));
    }
    Ok(())
}

/// The fewest bytes a stream of `count` elements can take, so a count the
/// stream can't hold is refused before the output is sized from it. An
/// ATTRIBUTES block takes a byte a lane at the least in v0 (its group
/// header) and only its control header in v1 (control mode 2 stores nothing),
/// a triangle takes its code byte, and an index its varint's byte.
fn fewest_bytes(count: usize, stride: usize, mode: Mode, v1: bool) -> usize {
    let data = match mode {
        Mode::Attributes => {
            let blocks = count.div_ceil(block_elements(stride));
            let tail = if v1 { (stride + stride / 4).max(TAIL_MIN_V1) } else { stride.max(TAIL_MIN_V0) };
            blocks.saturating_mul(if v1 { stride / 4 } else { stride }).saturating_add(tail)
        }
        Mode::Triangles => (count / 3).saturating_add(CODE_TABLE_LEN),
        Mode::Indices => count.saturating_add(INDICES_TAIL_LEN),
    };
    data.saturating_add(1)
}

/// Appendix A: `min((8192 / byteStride) & !15, 256)` elements a block.
fn block_elements(stride: usize) -> usize {
    ((8192 / stride) & !15).min(256)
}

/// A cursor over a stream's data: the bytes between its header (and, for
/// TRIANGLES, its codes) and its tail. Reading past them is the spec's "end
/// of stream too early".
struct Reader<'a> {
    data: &'a [u8],
    at: usize,
    end: usize,
    mode: Mode,
}

impl<'a> Reader<'a> {
    fn take(&mut self, n: usize) -> Result<&'a [u8], MeshError> {
        if n > self.end - self.at {
            return Err(ends_early(self.mode));
        }
        let bytes = &self.data[self.at..self.at + n];
        self.at += n;
        Ok(bytes)
    }

    fn byte(&mut self) -> Result<u8, MeshError> {
        Ok(self.take(1)?[0])
    }

    /// Appendix A's varint-7 (unsigned LEB128): one to five bytes, the top
    /// bit set on all but the last; bits past the 32nd are dropped.
    fn varint(&mut self) -> Result<u32, MeshError> {
        let mut v = 0u32;
        for group in 0..5 {
            let b = self.byte()?;
            v |= u32::from(b & 0x7f) << (7 * group);
            if b < 0x80 {
                return Ok(v);
            }
        }
        Err(malformed(format_args!("a {} varint runs past five bytes", self.mode.name())))
    }

    /// The spec's other invalid case: "any unprocessed bytes remain after
    /// decoding and before tail".
    fn finish(&self) -> Result<(), MeshError> {
        match self.end - self.at {
            0 => Ok(()),
            1 => Err(malformed(format_args!("the {} stream leaves 1 byte before its tail", self.mode.name()))),
            left => Err(malformed(format_args!("the {} stream leaves {left} bytes before its tail", self.mode.name()))),
        }
    }
}

fn unzigzag8(v: u8) -> u8 {
    (v >> 1) ^ 0u8.wrapping_sub(v & 1)
}

fn unzigzag16(v: u16) -> u16 {
    (v >> 1) ^ 0u16.wrapping_sub(v & 1)
}

fn unzigzag32(v: u32) -> u32 {
    (v >> 1) ^ 0u32.wrapping_sub(v & 1)
}

/// A v1 ATTRIBUTES stream's channel-mode bytes, the last `stride / 4` of its
/// tail: modes 0 (byte deltas) and 1 (2-byte deltas) take no rotation; mode
/// 2 (XOR) takes one in its high bits. "Streams that use channel mode 3 or
/// above, as well as streams that use channel mode 0 or 1 with high 4 bits
/// of the channel mode byte not equal to 0, are invalid." Checked before the
/// output is sized; `fewest_bytes` has held the stream to its tail.
fn check_channel_modes(data: &[u8], stride: usize) -> Result<(), MeshError> {
    for &channel in &data[data.len() - stride / 4..] {
        match channel & 0x0f {
            0 | 1 if channel >> 4 == 0 => {}
            2 => {}
            _ => return Err(malformed(format_args!("ATTRIBUTES channel mode byte 0x{channel:02x} is invalid"))),
        }
    }
    Ok(())
}

/// A TRIANGLES stream's 16-byte code table, its tail: the last two entries
/// are 0, and no entry has a half of 0xf, which would name no edge. Checked
/// before the output is sized; `fewest_bytes` has held the stream to its
/// tail.
fn check_code_table(data: &[u8]) -> Result<(), MeshError> {
    let table = &data[data.len() - CODE_TABLE_LEN..];
    if table[14] != 0 || table[15] != 0 {
        return Err(malformed(format_args!("the TRIANGLES code table's last two entries are 0x{:02x} 0x{:02x}, not 0", table[14], table[15])));
    }
    if let Some((i, e)) = table.iter().enumerate().find(|&(_, &e)| e >> 4 == 15 || e & 15 == 15) {
        return Err(malformed(format_args!("TRIANGLES code table entry {i} is 0x{e:02x}: neither half may be 0xf")));
    }
    Ok(())
}

/// Mode 0: blocks of byte-lane deltas, each lane in groups of 16 elements,
/// then the tail: the baseline element and, in v1, a channel mode for every
/// 4 bytes (checked by [`check_channel_modes`] before this runs).
fn decode_attributes(data: &[u8], count: usize, stride: usize, v1: bool, out: &mut [u8]) -> Result<(), MeshError> {
    let tail_len = if v1 { stride + stride / 4 } else { stride };
    let padded = tail_len.max(if v1 { TAIL_MIN_V1 } else { TAIL_MIN_V0 });
    let (baseline, channels) = data[data.len() - tail_len..].split_at(stride);
    let mut last = [0u8; 256];
    last[..stride].copy_from_slice(baseline);
    let block = block_elements(stride);
    let mut deltas = vec![0u8; block * stride];
    let mut r = Reader { data, at: 1, end: data.len() - padded, mode: Mode::Attributes };
    let mut start = 0;
    while start < count {
        let n = (count - start).min(block);
        let control = if v1 { r.take(stride / 4)? } else { &[][..] };
        for lane in 0..stride {
            let ctrl = if v1 { (control[lane / 4] >> (lane % 4 * 2)) & 3 } else { 0 };
            let lane_deltas = &mut deltas[lane * n..(lane + 1) * n];
            match ctrl {
                // v1 control mode 2: every delta 0, nothing stored; 3: the
                // deltas stored as they are, one byte each.
                2 => lane_deltas.fill(0),
                3 => lane_deltas.copy_from_slice(r.take(n)?),
                c => decode_lane(&mut r, lane_deltas, if v1 { &BITS_V1[usize::from(c)] } else { &BITS_V0 })?,
            }
        }
        for i in 0..n {
            let delta = |byte: usize| deltas[byte * n + i];
            for c in 0..stride / 4 {
                let at = c * 4;
                // v0 has no channel modes: every channel takes byte deltas.
                let channel = channels.get(c).copied().unwrap_or(0);
                match channel & 0x0f {
                    0 => {
                        for (b, v) in last[at..at + 4].iter_mut().enumerate() {
                            *v = v.wrapping_add(unzigzag8(delta(at + b)));
                        }
                    }
                    1 => {
                        for b in [at, at + 2] {
                            let d = unzigzag16(u16::from_le_bytes([delta(b), delta(b + 1)]));
                            let v = u16::from_le_bytes([last[b], last[b + 1]]).wrapping_add(d);
                            last[b..b + 2].copy_from_slice(&v.to_le_bytes());
                        }
                    }
                    // 2: a 4-byte XOR, rotated by the high bits
                    _ => {
                        let d = u32::from_le_bytes([delta(at), delta(at + 1), delta(at + 2), delta(at + 3)]);
                        let v = u32::from_le_bytes([last[at], last[at + 1], last[at + 2], last[at + 3]]) ^ d.rotate_right(u32::from(channel >> 4));
                        last[at..at + 4].copy_from_slice(&v.to_le_bytes());
                    }
                }
            }
            out[(start + i) * stride..(start + i + 1) * stride].copy_from_slice(&last[..stride]);
        }
        start += n;
    }
    r.finish()
}

/// One lane of one block: its group header bits (2 a group), then each
/// group at the bits its header mode gives.
fn decode_lane(r: &mut Reader<'_>, deltas: &mut [u8], bits: &[usize; 4]) -> Result<(), MeshError> {
    let header = r.take(deltas.len().div_ceil(16).div_ceil(4))?;
    for (g, group) in deltas.chunks_mut(16).enumerate() {
        let mode = (header[g / 4] >> (g % 4 * 2)) & 3;
        let decoded = decode_group(r, bits[usize::from(mode)])?;
        // A last group of fewer than 16 elements is decoded whole, and the
        // rest ignored.
        group.copy_from_slice(&decoded[..group.len()]);
    }
    Ok(())
}

/// Sixteen deltas at `bits` each. At 1, 2 and 4 bits a delta of all ones is
/// the sentinel: the real delta follows as a byte, after the packed bits.
fn decode_group(r: &mut Reader<'_>, bits: usize) -> Result<[u8; 16], MeshError> {
    let mut group = [0u8; 16];
    match bits {
        0 => {}
        8 => group.copy_from_slice(r.take(16)?),
        _ => {
            let packed = r.take(2 * bits)?;
            let sentinel = (1u8 << bits) - 1;
            for (m, delta) in group.iter_mut().enumerate() {
                // 1 bit: least significant first; 2 and 4 bits: most
                // significant first.
                let v = match bits {
                    1 => (packed[m / 8] >> (m % 8)) & 1,
                    2 => (packed[m / 4] >> (6 - 2 * (m % 4))) & 3,
                    _ => (packed[m / 2] >> (4 - 4 * (m % 2))) & 15,
                };
                *delta = if v == sentinel { r.byte()? } else { v };
            }
        }
    }
    Ok(group)
}

/// A 16-entry FIFO that counts what was written to it: "Any streams that
/// require the decoder to read an edge or vertex FIFO entry that was not
/// previously written are invalid."
struct Fifo<T> {
    entries: [T; 16],
    next: usize,
    written: usize,
}

impl<T: Copy + Default> Fifo<T> {
    fn new() -> Self {
        Fifo { entries: [T::default(); 16], next: 0, written: 0 }
    }

    fn push(&mut self, v: T) {
        self.entries[self.next] = v;
        self.next = (self.next + 1) % 16;
        self.written = (self.written + 1).min(16);
    }

    /// The entry `age` pushes back (0 is the latest), if one was written.
    fn get(&self, age: usize) -> Option<T> {
        if age < self.written {
            Some(self.entries[(self.next + 15 - age) % 16])
        } else {
            None
        }
    }
}

fn unwritten(code: u8, fifo: &str, age: u8) -> MeshError {
    malformed(format_args!("TRIANGLES code 0x{code:02x} reads {fifo} FIFO entry {age}, which no triangle wrote"))
}

fn bump(next: &mut u32) -> u32 {
    let v = *next;
    *next = next.wrapping_add(1);
    v
}

/// An index coded as a zig-zag delta from `last`, which it becomes.
fn free_index(r: &mut Reader<'_>, last: &mut u32) -> Result<u32, MeshError> {
    *last = last.wrapping_add(unzigzag32(r.varint()?));
    Ok(*last)
}

fn write_index(out: &mut [u8], stride: usize, i: usize, v: u32) {
    if stride == 2 {
        // 16-bit output wraps, as the spec says.
        out[i * 2..i * 2 + 2].copy_from_slice(&(v as u16).to_le_bytes());
    } else {
        out[i * 4..i * 4 + 4].copy_from_slice(&v.to_le_bytes());
    }
}

/// Mode 1: a code byte per triangle, then the data some codes read, then a
/// 16-byte code table.
fn decode_triangles(data: &[u8], count: usize, stride: usize, out: &mut [u8]) -> Result<(), MeshError> {
    let triangles = count / 3;
    let codes = &data[1..1 + triangles];
    let table = &data[data.len() - CODE_TABLE_LEN..];
    let mut r = Reader { data, at: 1 + triangles, end: data.len() - CODE_TABLE_LEN, mode: Mode::Triangles };
    let mut edges: Fifo<(u32, u32)> = Fifo::new();
    let mut vertices: Fifo<u32> = Fifo::new();
    let (mut next, mut last) = (0u32, 0u32);
    for (t, &code) in codes.iter().enumerate() {
        let (high, low) = (code >> 4, code & 15);
        let vertex = |vertices: &Fifo<u32>, age: u8| vertices.get(usize::from(age)).ok_or_else(|| unwritten(code, "vertex", age));
        let [a, b, c] = if high < 15 {
            // 0xXY: edge X, then the third index by Y.
            let (a, b) = edges.get(usize::from(high)).ok_or_else(|| unwritten(code, "edge", high))?;
            let c = match low {
                0 => bump(&mut next),
                1..=12 => vertex(&vertices, low)?,
                13 => {
                    last = last.wrapping_sub(1);
                    last
                }
                14 => {
                    last = last.wrapping_add(1);
                    last
                }
                _ => free_index(&mut r, &mut last)?,
            };
            // A new, adjacent (last ± 1) or explicit index joins the vertex
            // FIFO; one read from it doesn't.
            if low == 0 || low >= 13 {
                vertices.push(c);
            }
            edges.push((c, b));
            edges.push((a, c));
            [a, b, c]
        } else {
            // 0xfY (Y < 14) takes its 0xZW from the code table's entry Y;
            // 0xfe and 0xff read it from the data, where 0 resets `next`, and
            // 0xff codes its first index explicitly. Z and W then give the
            // second and third indices: 0 is the next new index, 0xf (0xfe
            // and 0xff only) one coded explicitly, and any other value the
            // vertex FIFO entry before it.
            let explicit = low >= 14;
            let zw = if explicit { r.byte()? } else { table[usize::from(low)] };
            if explicit && zw == 0 {
                next = 0;
            }
            let a = if low == 15 { free_index(&mut r, &mut last)? } else { bump(&mut next) };
            let mut third = |half: u8| match half {
                0 => Ok(bump(&mut next)),
                15 => free_index(&mut r, &mut last),
                _ => vertex(&vertices, half - 1),
            };
            let (z, w) = (zw >> 4, zw & 15);
            let b = third(z)?;
            let c = third(w)?;
            vertices.push(a);
            if z == 0 || z == 15 {
                vertices.push(b);
            }
            if w == 0 || w == 15 {
                vertices.push(c);
            }
            edges.push((b, a));
            edges.push((c, b));
            edges.push((a, c));
            [a, b, c]
        };
        for (k, v) in [a, b, c].into_iter().enumerate() {
            write_index(out, stride, t * 3 + k, v);
        }
    }
    r.finish()
}

/// Mode 2: a varint per index, its low bit choosing one of two baselines
/// and the rest a zig-zag delta from it.
fn decode_indices(data: &[u8], count: usize, stride: usize, out: &mut [u8]) -> Result<(), MeshError> {
    let mut r = Reader { data, at: 1, end: data.len() - INDICES_TAIL_LEN, mode: Mode::Indices };
    let mut last = [0u32; 2];
    for i in 0..count {
        let v = r.varint()?;
        let baseline = (v & 1) as usize;
        let delta = if v & 2 != 0 { !(v >> 2) } else { v >> 2 };
        last[baseline] = last[baseline].wrapping_add(delta);
        write_index(out, stride, i, last[baseline]);
    }
    r.finish()
}

/// Appendix B, element by element, in place. Each filter's stride was
/// checked by `check_layout`.
fn apply_filter(out: &mut [u8], stride: usize, filter: Filter) {
    match filter {
        Filter::None => {}
        Filter::Octahedral if stride == 4 => {
            for e in out.chunks_exact_mut(4) {
                let n = octahedral([e[0], e[1], e[2]].map(|c| f32::from(c as i8)), 127.0);
                for (k, v) in n.into_iter().enumerate() {
                    e[k] = v as i8 as u8;
                }
            }
        }
        Filter::Octahedral => {
            for e in out.chunks_exact_mut(8) {
                let n = octahedral([0, 2, 4].map(|k| f32::from(i16::from_le_bytes([e[k], e[k + 1]]))), 32767.0);
                for (k, v) in n.into_iter().enumerate() {
                    e[k * 2..k * 2 + 2].copy_from_slice(&(v as i16).to_le_bytes());
                }
            }
        }
        Filter::Quaternion => {
            for e in out.chunks_exact_mut(8) {
                let q = quaternion([0, 2, 4, 6].map(|k| i16::from_le_bytes([e[k], e[k + 1]])));
                for (k, v) in q.into_iter().enumerate() {
                    e[k * 2..k * 2 + 2].copy_from_slice(&v.to_le_bytes());
                }
            }
        }
        Filter::Exponential => {
            for e in out.chunks_exact_mut(4) {
                let v = exponential(u32::from_le_bytes([e[0], e[1], e[2], e[3]]));
                e.copy_from_slice(&v.to_le_bytes());
            }
        }
        Filter::Color if stride == 4 => {
            for e in out.chunks_exact_mut(4) {
                let rgba = color(i32::from(e[0]), i32::from(e[1] as i8), i32::from(e[2] as i8), u32::from(e[3]), 255.0);
                for (k, v) in rgba.into_iter().enumerate() {
                    e[k] = v as u8;
                }
            }
        }
        Filter::Color => {
            for e in out.chunks_exact_mut(8) {
                let [y, co, cg, alpha] = [0, 2, 4, 6].map(|k| u16::from_le_bytes([e[k], e[k + 1]]));
                let rgba = color(i32::from(y), i32::from(co as i16), i32::from(cg as i16), u32::from(alpha), 65535.0);
                for (k, v) in rgba.into_iter().enumerate() {
                    e[k * 2..k * 2 + 2].copy_from_slice(&(v as u16).to_le_bytes());
                }
            }
        }
    }
}

/// Filter 1: x and y in octahedral encoding over the third component, which
/// encodes 1.0, to a unit vector at `max` (`INTN_MAX`). The fourth component
/// is the caller's to keep.
fn octahedral([x, y, one]: [f32; 3], max: f32) -> [i32; 3] {
    let (mut x, mut y) = (x / one, y / one);
    let z = 1.0 - x.abs() - y.abs();
    // The fixup for the negative hemisphere, in the reference decoder's
    // form (`x >= 0 ? t : -t`), which takes -0.0 as positive; `copysign`
    // would take it as negative (Ruling B51).
    let t = (-z).max(0.0);
    x -= if x >= 0.0 { t } else { -t };
    y -= if y >= 0.0 { t } else { -t };
    let len = (x * x + y * y + z * z).sqrt();
    [x, y, z].map(|c| (c / len * max).round() as i32)
}

/// Filter 2: the three smallest components, scaled by sqrt(2), and 1.0
/// whose low two bits name the largest, to the four components.
fn quaternion(q: [i16; 4]) -> [i16; 4] {
    let one = f32::from(q[3] | 3);
    let [x, y, z] = [q[0], q[1], q[2]].map(|c| f32::from(c) / one * std::f32::consts::FRAC_1_SQRT_2);
    let w = (1.0 - x * x - y * y - z * z).max(0.0).sqrt();
    let largest = (q[3] & 3) as usize;
    let mut out = [0i16; 4];
    for (k, v) in [(1, x), (2, y), (3, z), (0, w)] {
        out[(largest + k) % 4] = (v * 32767.0).round() as i32 as i16;
    }
    out
}

/// Filter 3: `2^e × m`, from an 8-bit exponent over a 24-bit mantissa, both
/// signed. 2^e is built from its bits, as meshoptimizer's decoders build it,
/// which is exact for the valid exponents (-100 to 100). Others, which the
/// spec leaves unspecified, decode as theirs do.
fn exponential(v: u32) -> u32 {
    let e = (v as i32) >> 24;
    let m = ((v << 8) as i32) >> 8;
    (f32::from_bits(((e + 127) as u32) << 23) * m as f32).to_bits()
}

/// Filter 4: Y, Co, Cg and alpha (its top bit gives K) to RGBA at `full`
/// (`UINTN_MAX`).
fn color(y: i32, co: i32, cg: i32, alpha: u32, full: f32) -> [i32; 4] {
    // findMSB: -1 for 0
    let top = 31 - alpha.leading_zeros() as i32;
    let scale = (1i32 << (top + 1)) - 1;
    let a = alpha as i32 & (scale >> 1);
    let ss = full / scale as f32;
    [y + co - cg, y + cg, y - co - cg, (a << 1) | (a & 1)].map(|c| (c as f32 * ss).round() as i32)
}

