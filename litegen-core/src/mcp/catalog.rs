//! The tool catalog. Every operation of the HTTP API is either an MCP tool
//! here, on the endpoint and toolset it belongs to and with the gate its route
//! enforces, or excluded with a reason. A unit test keeps this list in step
//! with `/openapi.json`, so a new endpoint can never be silently missing.

use super::Surface;
use crate::api::middleware::Scope;
use crate::auth::permissions::Permission;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Http {
    Get,
    Post,
    Put,
    Patch,
    Delete,
}

impl Http {
    pub fn as_str(self) -> &'static str {
        match self {
            Http::Get => "GET",
            Http::Post => "POST",
            Http::Put => "PUT",
            Http::Patch => "PATCH",
            Http::Delete => "DELETE",
        }
    }

    pub fn method(self) -> axum::http::Method {
        match self {
            Http::Get => axum::http::Method::GET,
            Http::Post => axum::http::Method::POST,
            Http::Put => axum::http::Method::PUT,
            Http::Patch => axum::http::Method::PATCH,
            Http::Delete => axum::http::Method::DELETE,
        }
    }
}

/// The endpoint(s) a tool is listed on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Surfaces {
    Ai,
    Admin,
    Both,
}

impl Surfaces {
    pub fn includes(self, surface: Surface) -> bool {
        matches!((self, surface), (Surfaces::Both, _) | (Surfaces::Ai, Surface::Ai) | (Surfaces::Admin, Surface::Admin))
    }
}

/// The check a tool's HTTP route performs; `gate::visible` mirrors it.
#[derive(Debug, Clone, Copy)]
pub enum Gate {
    /// `check_scope` on the route group.
    Scope(Scope),
    /// `check_any_scope` on the route group.
    AnyScope(&'static [Scope]),
    /// `management::require_org` for a read.
    OrgRead(Permission),
    /// `management::require_org` for a write.
    OrgWrite(Permission),
    /// `orgs::require_member_perm`: signed-in members (or the platform admin).
    Member(Permission),
    /// The handler checks the caller's own permissions (`users::invite_user`).
    Perm(Permission),
    /// `users::authorize_global_user_admin`.
    Global(Permission),
    /// `management::require_gateway_admin`.
    GatewayAdmin,
    /// `check_scope` on the route group, plus `require_deployment_reader` on
    /// the route: the deployment's own state (hosted: the platform admin).
    Deployment(Scope),
    /// The handler needs a signed-in user.
    User,
    /// Any authenticated caller.
    Any,
}

#[derive(Debug)]
pub struct ToolDef {
    pub name: &'static str,
    pub method: Http,
    /// The OpenAPI path, e.g. `/v1/models/{id}`.
    pub path: &'static str,
    pub surfaces: Surfaces,
    pub toolset: &'static str,
    pub gate: Gate,
    pub title: &'static str,
    /// Replaces the OpenAPI summary and description when set.
    pub description: Option<&'static str>,
    /// The path parameter whose `/` must reach the route unescaped (model ids).
    pub catch_all: Option<&'static str>,
}

/// An operation deliberately left out of MCP.
#[derive(Debug)]
pub struct Excluded {
    pub method: Http,
    pub path: &'static str,
    pub reason: &'static str,
}

